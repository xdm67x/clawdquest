// ---------------------------------------------------------------------------
// mkfont: rasterize a system font into a compact atlas and emit a C header.
//
// The Quest Log C port draws all text with an embedded bitmap atlas, so the
// binary has no runtime font dependency. This tool is run once (and whenever
// the atlas needs regenerating); its output src/font_atlas.h is committed.
//
// Coverage is stored at 4 bits per pixel, base64-encoded in the header and
// decoded at startup. Cell layout:
//
//   FA_FIRST .. glyphs packed row-major into a FA_COLS x FA_ROWS grid
//   FA_CW x FA_CH cell, glyph origin at (FA_BASE x, FA_BASE y) from cell top.
//
// Build: make font   (needs freetype; brew install freetype)
// ---------------------------------------------------------------------------

#include <stdio.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

#include <ft2build.h>
#include FT_FREETYPE_H

// Which codepoints go into the atlas: printable ASCII plus a few glyphs the
// UI needs (checkmark, multiplication cross, bullet, arrow).
static const uint32_t CHARS[] = {
    0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x28, 0x29, 0x2a, 0x2b,
    0x2c, 0x2d, 0x2e, 0x2f, 0x30, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37,
    0x38, 0x39, 0x3a, 0x3b, 0x3c, 0x3d, 0x3e, 0x3f, 0x40, 0x41, 0x42, 0x43,
    0x44, 0x45, 0x46, 0x47, 0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f,
    0x50, 0x51, 0x52, 0x53, 0x54, 0x55, 0x56, 0x57, 0x58, 0x59, 0x5a, 0x5b,
    0x5c, 0x5d, 0x5e, 0x5f, 0x60, 0x61, 0x62, 0x63, 0x64, 0x65, 0x66, 0x67,
    0x68, 0x69, 0x6a, 0x6b, 0x6c, 0x6d, 0x6e, 0x6f, 0x70, 0x71, 0x72, 0x73,
    0x74, 0x75, 0x76, 0x77, 0x78, 0x79, 0x7a, 0x7b, 0x7c, 0x7d, 0x7e,
    0xd7,   // multiplication sign: the quest delete "x"
    0x2022, // bullet
    0x2191, // up arrow: level-up toasts
    0x2713, // checkmark: quest done
    0x2715, // multiplication X: delete button glyph
};
#define NCHARS ((int)(sizeof CHARS / sizeof CHARS[0]))

#define PX 28      // raster size; the HUD draws most text around half this
#define COLS 16    // glyphs per atlas row
#define CW 30      // cell width
#define CH 38      // cell height
#define BASE 26    // baseline, in pixels from cell top
#define ROWS ((NCHARS + COLS - 1) / COLS)
#define AW (COLS * CW)
#define AH (ROWS * CH)

static uint8_t cov[AH][AW]; // 8-bit coverage per atlas pixel
static uint8_t adv[NCHARS];

static const char *b64 =
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

int main(int argc, char **argv) {
    const char *path = argc > 1 ? argv[1] : "/System/Library/Fonts/Helvetica.ttc";
    const char *out = argc > 2 ? argv[2] : "src/font_atlas.h";

    FT_Library ft;
    if (FT_Init_FreeType(&ft)) { fprintf(stderr, "freetype init failed\n"); return 1; }
    FT_Face face;
    if (FT_New_Face(ft, path, 0, &face)) { fprintf(stderr, "cannot open %s\n", path); return 1; }
    if (FT_Set_Pixel_Sizes(face, 0, PX)) { fprintf(stderr, "cannot size %s\n", path); return 1; }

    for (int g = 0; g < NCHARS; g++) {
        if (FT_Load_Char(face, CHARS[g], FT_LOAD_RENDER)) continue;
        FT_GlyphSlot s = face->glyph;
        FT_Bitmap *b = &s->bitmap;
        int gx = s->bitmap_left, gy = BASE - s->bitmap_top;
        adv[g] = (uint8_t)((s->advance.x + 32) >> 6);
        int bw = b->width < CW ? b->width : CW, bh = b->rows < CH ? b->rows : CH;
        for (int y = 0; y < bh; y++) {
            if (gy + y < 0 || gy + y >= CH) continue;
            for (int x = 0; x < bw; x++) {
                int ax = (g % COLS) * CW + gx + x;
                if (ax < 0 || ax >= AW) continue;
                cov[(g / COLS) * CH + gy + y][ax] = b->buffer[y * b->pitch + x];
            }
        }
    }
    FT_Done_Face(face);
    FT_Done_FreeType(ft);

    // Pack coverage to 4 bits per pixel, then base64.
    int nib = AW * AH;
    uint8_t *packed = malloc((size_t)((nib + 1) / 2));
    for (int i = 0; i < nib; i++) {
        int v = cov[i / AW][i % AW] >> 4;
        if (i & 1) packed[i / 2] |= (uint8_t)(v << 4);
        else packed[i / 2] = (uint8_t)v;
    }
    int nb = (nib + 1) / 2;
    int b64n = (nb + 2) / 3 * 4;
    char *enc = malloc((size_t)b64n + 1);
    for (int i = 0, e = 0; i < nb; i += 3) {
        uint32_t v = (uint32_t)packed[i] << 16;
        if (i + 1 < nb) v |= (uint32_t)packed[i + 1] << 8;
        if (i + 2 < nb) v |= packed[i + 2];
        enc[e++] = b64[(v >> 18) & 63];
        enc[e++] = b64[(v >> 12) & 63];
        enc[e++] = (i + 1 < nb) ? b64[(v >> 6) & 63] : '=';
        enc[e++] = (i + 2 < nb) ? b64[v & 63] : '=';
    }
    enc[b64n] = 0;

    FILE *f = fopen(out, "w");
    if (!f) { perror(out); return 1; }
    fprintf(f,
        "// Generated by tools/mkfont.c — do not edit.\n"
        "// %s at %dpx, %d glyphs in a %dx%d grid of %dx%d cells.\n"
        "// Coverage packed at 4bpp, base64. Glyph origin: (%d, %d) per cell.\n"
        "#pragma once\n\n"
        "#define FA_COUNT %d\n"
        "#define FA_COLS %d\n"
        "#define FA_ROWS %d\n"
        "#define FA_CW %d\n"
        "#define FA_CH %d\n"
        "#define FA_BASE %d\n"
        "#define FA_W %d\n"
        "#define FA_H %d\n\n",
        path, PX, NCHARS, COLS, ROWS, CW, CH, 0, BASE,
        NCHARS, COLS, ROWS, CW, CH, BASE, AW, AH);

    fprintf(f, "// Codepoints, same order as atlas cells.\nstatic const unsigned int FA_CHARS[FA_COUNT] = {\n");
    for (int g = 0; g < NCHARS; g++)
        fprintf(f, "0x%x,%s", CHARS[g], (g % 12 == 11 || g == NCHARS - 1) ? "\n" : " ");
    fprintf(f, "};\n\n// Advance in pixels at the raster size.\nstatic const unsigned char FA_ADV[FA_COUNT] = {\n");
    for (int g = 0; g < NCHARS; g++)
        fprintf(f, "%d,%s", adv[g], (g % 16 == 15 || g == NCHARS - 1) ? "\n" : " ");
    fprintf(f, "};\n\n// Atlas coverage, 4bpp big-endian nibble order, base64.\n#define FA_B64_LEN %d\nstatic const char FA_B64[] =\n\"", b64n);
    for (int i = 0; i < b64n; i++) {
        if (i && i % 100 == 0) fputc('\"', f), fputc('\n', f), fputc('\"', f);
        fputc(enc[i], f);
    }
    fprintf(f, "\";\n");
    fclose(f);
    fprintf(stderr, "wrote %s (%d x %d, %d base64 chars)\n", out, AW, AH, b64n);
    return 0;
}
